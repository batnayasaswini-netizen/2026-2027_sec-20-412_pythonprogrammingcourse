# Demonstration of Type Conversion

# Integer to Float
a = 10
b = float(a)
print("Integer to Float:", b)

# Float to Integer
c = 12.5
d = int(c)
print("Float to Integer:", d)

# Integer to String
e = 25
f = str(e)
print("Integer to String:", f)

# String to Integer
g = "100"
h = int(g)
print("String to Integer:", h)

# String to Float
i = "45.6"
j = float(i)
print("String to Float:", j)

# Float to String
k = 3.14
l = str(k)
print("Float to String:", l)