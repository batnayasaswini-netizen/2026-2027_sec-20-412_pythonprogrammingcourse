# Program to demonstrate membership operators

list1 = [10, 20, 30, 40, 50]

print("List:", list1)

# Using 'in' operator
print("20 in list1:", 20 in list1)
print("60 in list1:", 60 in list1)

# Using 'not in' operator
print("60 not in list1:", 60 not in list1)
print("30 not in list1:", 30 not in list1)